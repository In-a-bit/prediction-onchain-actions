#!/usr/bin/env bash
# Regenerates the "Load Test Stack" section at the bottom of .env from the
# load-test stack's own sources of truth, instead of hand-copying addresses
# after every `lt snapshot-bake` / `lt anvil-wipe` redeploy:
#   - apps/load-test/.env.loadtest        (admin/owner keys, API keys, ports)
#   - contracts/out/addresses.json        (deployed contract addresses,
#     read from inside the loadtest-runner container — it's a named Docker
#     volume, not bind-mounted to the host)
#
# A plain anvil restart (`?what=anvil-restart` / the UI's "restart anvil, keep
# state" button) does NOT change addresses — .anvil-state.json is preserved,
# so nothing to sync. Only a fresh bake/wipe (new deploy) invalidates them.
#
# Usage: ./scripts/sync-loadtest-env.sh [path-to-prediction-bundler-checkout]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/../.env"
BUNDLER_DIR="${1:-${PREDICTION_BUNDLER_DIR:-$SCRIPT_DIR/../../prediction-bundler}}"
ENV_LOADTEST="$BUNDLER_DIR/apps/load-test/.env.loadtest"
CONTAINER="${LOADTEST_CONTAINER:-loadtest-runner}"

[[ -f "$ENV_LOADTEST" ]] || { echo "ERROR: $ENV_LOADTEST not found (pass the prediction-bundler path as \$1, or set PREDICTION_BUNDLER_DIR)" >&2; exit 1; }
docker exec "$CONTAINER" true 2>/dev/null || { echo "ERROR: container '$CONTAINER' is not running" >&2; exit 1; }

# dotenv semantics: the LAST assignment of a key wins, so read backwards.
# `|| true` — grep exits 1 on no match (e.g. ANVIL_PORT isn't set, it just
# falls back to anvil's own default), which would otherwise trip set -e.
lt_env() { grep "^$1=" "$ENV_LOADTEST" | tail -1 | cut -d= -f2- || true; }

ADDRESSES_JSON="$(docker exec "$CONTAINER" cat /app/apps/load-test/contracts/out/addresses.json)"
addr() { echo "$ADDRESSES_JSON" | jq -r ".$1"; }

GAMMA_API_PORT="$(lt_env GAMMA_API_PORT)"; GAMMA_API_PORT="${GAMMA_API_PORT:-9084}"
DPM_API_PORT="$(lt_env DPM_API_PORT)"; DPM_API_PORT="${DPM_API_PORT:-9086}"
ANVIL_PORT="$(lt_env ANVIL_PORT)"; ANVIL_PORT="${ANVIL_PORT:-8545}"

NEW_SECTION="$(cat <<EOF
###################################################
#
################# Load Test Stack #################
#
###################################################
# Everything below overrides the Amoy/dev values above (dotenv keeps the
# last-seen value per key) so this app talks to the load-test stack's local
# anvil fork instead of Amoy. The Amoy block above is left untouched — to go
# back to Amoy, just delete/comment this whole section.
#
# CAUTION — these addresses/keys are tied to the CURRENT load-test bake.
# Regenerated by scripts/sync-loadtest-env.sh on $(date -u +%Y-%m-%d) from
# apps/load-test/.env.loadtest + contracts/out/addresses.json. A fresh
# \`lt snapshot-bake\` / \`anvil-wipe\` redeploys everything with new
# addresses/keys — re-run this script afterwards. A plain anvil restart
# ("keep state") does NOT change addresses; no sync needed for that.

# DPM API / Gamma API (load-test stack)
NEXT_PUBLIC_GAMMA_API_BASE_URL=http://127.0.0.1:$GAMMA_API_PORT
NEXT_PUBLIC_DPM_API_BASE_URL=http://127.0.0.1:$DPM_API_PORT
DPM_API_KEY=$(lt_env DPM_API_KEY)
APP_API_KEY=$(lt_env APP_API_KEY)

# RPC — load-test's local anvil (fork of Polygon MAINNET, chain id 137 — not
# Amoy). ethers' JsonRpcProvider auto-detects the chain id, no code change
# needed.
RPC_URL=http://127.0.0.1:$ANVIL_PORT

# Relayer EOA
RELAYER_EOA_ADDRESS=$(lt_env RELAYER_EOA_ADDRESS)
RELAYER_EOA_PRIVATE_KEY=$(lt_env RELAYER_EOA_PRIVATE_KEY)

# CTF Exchange
CTF_EXCHANGE_ADDRESS=$(addr exchange)
CTF_EXCHANGE_ADMIN_ADDRESS=$(lt_env CTF_EXCHANGE_ADMIN_ADDRESS)
CTF_EXCHANGE_ADMIN_PRIVATE_KEY=$(lt_env CTF_EXCHANGE_ADMIN_PRIVATE_KEY)

# Fee Module
FEE_MODULE_ADDRESS=$(addr feeModule)
FEE_MODULE_ADMIN_ADDRESS=$(lt_env FEE_MODULE_ADMIN_ADDRESS)
FEE_MODULE_ADMIN_PRIVATE_KEY=$(lt_env FEE_MODULE_ADMIN_PRIVATE_KEY)

# Oracle Whitelist (requesterWhitelist)
ORACLE_WHITELIST_ADDRESS=$(addr requesterWhitelist)
ORACLE_WHITELIST_OWNER_ADDRESS=$(lt_env ORACLE_WHITELIST_OWNER_ADDRESS)
ORACLE_WHITELIST_OWNER_PRIVATE_KEY=$(lt_env ORACLE_WHITELIST_OWNER_PRIVATE_KEY)

# Managed Optimistic Oracle Proxy — owner is DEPLOYER_ADDR (verified on-chain
# via owner(); setup-seed-admins never transfers this one, only the
# whitelists), not a dedicated seed-admin role.
MANAGED_OPTIMISTIC_ORACLE_PROXY_ADDRESS=$(addr managedOO)
MANAGED_OPTIMISTIC_ORACLE_PROXY_OWNER_ADDRESS=$(lt_env DEPLOYER_ADDR)
MANAGED_OPTIMISTIC_ORACLE_PROXY_OWNER_PRIVATE_KEY=$(lt_env DEPLOYER_PK)

# RelayHub
RELAY_HUB_ADDRESS=$(addr relayHub)

# ProxyWalletFactory
PROXY_WALLET_FACTORY_ADDRESS=$(addr proxyFactory)

# Collateral Token — real mainnet USDC.e (the fork carries live mainnet
# state), NOT the Amoy testnet USDC address above.
COLLATERAL_ADDRESS=$(addr usdc)

# Conditional Tokens — same address as the Amoy block above by coincidence:
# this is the real, already-deployed Polymarket mainnet CT contract, forked
# in as-is rather than redeployed by load-test.
CONDITIONAL_TOKENS_ADDRESS=$(addr ctf)

# UmaCtfAdapter
UMA_CTF_ADAPTER_ADDRESS=$(addr umaCtfAdapter)
UMA_CTF_ADAPTER_ADMIN_ADDRESS=$(lt_env UMA_CTF_ADAPTER_ADMIN_ADDRESS)
UMA_CTF_ADAPTER_ADMIN_PRIVATE_KEY=$(lt_env UMA_CTF_ADAPTER_ADMIN_PRIVATE_KEY)

# Treasury
TREASURY_ADDRESS=$(addr treasury)
TREASURY_ADMIN_ADDRESS=$(lt_env TREASURY_ADMIN_ADDRESS)
TREASURY_ADMIN_PRIVATE_KEY=$(lt_env TREASURY_ADMIN_PRIVATE_KEY)

# CTF Oracle — admin is DEPLOYER_ADDR (CtfOracle.sol's constructor grants the
# deployer admin; load-test's setup-seed-admins never calls addAdmin for this
# contract, unlike FeeModule/Exchange/UmaCtfAdapter).
CTF_ORACLE_ADDRESS=$(addr ctfOracle)
CTF_ORACLE_ADMIN_ADDRESS=$(lt_env DEPLOYER_ADDR)
CTF_ORACLE_ADMIN_PRIVATE_KEY=$(lt_env DEPLOYER_PK)
EOF
)"

MARKER='################# Load Test Stack #################'
if grep -qF "$MARKER" "$ENV_FILE"; then
  # Keep everything before the 3-line banner above the marker (marker line -2
  # is the banner's top "###" line, so stop 1 line earlier), trimming
  # trailing blank lines, then append the freshly generated section.
  MARKER_LINE=$(grep -nF "$MARKER" "$ENV_FILE" | head -1 | cut -d: -f1)
  BEFORE_LINE=$(( MARKER_LINE - 3 ))
  head -n "$BEFORE_LINE" "$ENV_FILE" | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' > "$ENV_FILE.tmp"
else
  cp "$ENV_FILE" "$ENV_FILE.tmp"
fi

{
  cat "$ENV_FILE.tmp"
  echo
  echo "$NEW_SECTION"
} > "$ENV_FILE.new"
rm -f "$ENV_FILE.tmp"
mv "$ENV_FILE.new" "$ENV_FILE"

echo "Synced Load Test Stack section in $ENV_FILE from:"
echo "  - $ENV_LOADTEST"
echo "  - $CONTAINER:/app/apps/load-test/contracts/out/addresses.json"
